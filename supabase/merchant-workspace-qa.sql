-- 回滚式验收：只写入测试数据，完成后全部 ROLLBACK，不修改现有订单。
begin;
select set_config('app.qa_merchant',(select id::text from public.profiles where role='merchant' and is_active limit 1),true);
select set_config('app.qa_admin',(select id::text from public.profiles where role='admin' and is_active limit 1),true);
select set_config('app.qa_warehouse',(select id::text from public.profiles where role='warehouse_operator' and is_active limit 1),true);
create temporary table qa_workspace_results(test text, result text);
grant select,insert on qa_workspace_results to authenticated;
set local role authenticated;
do $$
declare
 m uuid := current_setting('app.qa_merchant')::uuid;
 a uuid := current_setting('app.qa_admin')::uuid;
 w uuid := current_setting('app.qa_warehouse')::uuid;
 addr uuid; p public.parcels; o public.orders; f public.fees; t uuid; rejected boolean;
 n text := 'QA-'||replace(gen_random_uuid()::text,'-','');
begin
 if m is null or a is null or w is null then raise exception '验收需要现有商家、仓库、管理员账号'; end if;
 perform set_config('request.jwt.claim.sub',m::text,true);
 p := public.merchant_pre_advise(n,'QA回滚测试包裹','测试快递');
 if p.merchant_id<>m or p.status<>'pre_advised' then raise exception '预报归属或状态异常'; end if;
 insert into qa_workspace_results values('预报与归属','PASS');
 insert into public.merchant_addresses(merchant_id,label,recipient_name,recipient_phone,country,city,address_line)
 values(m,'QA回滚地址','QA测试收件人','00000000000','印度尼西亚','Jakarta','QA测试地址，不可发货') returning id into addr;
 perform set_config('request.jwt.claim.sub',w::text,true);
 p := public.warehouse_receive_parcel(p.id);
 if p.status<>'received' then raise exception '独立入库失败'; end if;
 insert into qa_workspace_results values('独立包裹先入库后申请打包','PASS');
 perform set_config('request.jwt.claim.sub',m::text,true);
 o := public.merchant_create_from_parcels(array[p.id],addr,'ID-AIR','合并为一个外箱','QA回滚测试，请勿发货');
 if o.merchant_id<>m or not o.consolidated or o.parcel_count<>1 or o.status<>'submitted' then raise exception '合包关联异常'; end if;
 insert into qa_workspace_results values('合包创建与真实包裹关联','PASS');
 rejected:=false;
 begin perform public.merchant_create_from_parcels(array[p.id],addr,'ID-AIR','合并为一个外箱',null); exception when others then rejected:=true; end;
 if not rejected then raise exception '重复申请未拦截'; end if;
 insert into qa_workspace_results values('重复合包拦截','PASS');
 perform set_config('request.jwt.claim.sub',gen_random_uuid()::text,true);
 if exists(select 1 from public.orders where id=o.id) or exists(select 1 from public.parcels where id=p.id) then raise exception '跨商家读取未拦截'; end if;
 rejected:=false;
 begin perform public.merchant_submit_consolidation(o.id,'合并为一个外箱',null); exception when others then rejected:=true; end;
 if not rejected then raise exception '跨商家修改未拦截'; end if;
 insert into qa_workspace_results values('跨商家读取和修改隔离','PASS');
 perform set_config('request.jwt.claim.sub',w::text,true);
 rejected:=false;
 begin perform public.merchant_pre_advise(n||'-staff','QA仓库越权',null); exception when others then rejected:=true; end;
 if not rejected then raise exception '仓库商家RPC越权未拦截'; end if;
 insert into qa_workspace_results values('仓库角色越权拦截','PASS');
 perform public.warehouse_receive_order(o.id);
 f := public.warehouse_confirm_measurements(o.id,jsonb_build_array(jsonb_build_object('parcel_no',p.parcel_no,'actual_weight_kg',2,'length_cm',10,'width_cm',10,'height_cm',10)));
 if f.total_amount<>(select round(first_price+greatest(2-first_weight_kg,0)*additional_price_per_kg,2)+handling_fee from public.route_pricing where route_code='ID-AIR') then raise exception '确认费率不一致'; end if;
 insert into qa_workspace_results values('仓库收货测量与运价一致','PASS');
 rejected:=false;
 begin perform public.warehouse_pack_order(o.id,'QA-BOX',null); exception when others then rejected:=true; end;
 if not rejected then raise exception '未付款打包未拦截'; end if;
 insert into qa_workspace_results values('未付款打包门禁','PASS');
 perform set_config('request.jwt.claim.sub',m::text,true);
 perform public.record_order_payment(o.id,'manual_transfer','qa_rollback',null);
 rejected:=false;
 begin perform public.record_order_payment(o.id,'manual_transfer','qa_rollback',null); exception when others then rejected:=true; end;
 if not rejected then raise exception '重复付款未拦截'; end if;
 perform set_config('request.jwt.claim.sub',w::text,true);
 perform public.warehouse_pack_order(o.id,'QA-BOX','QA回滚打包');
 perform public.warehouse_ship_order(o.id,'QA测试承运商','QA-TEST-TRACKING');
 perform set_config('request.jwt.claim.sub',m::text,true);
 if not exists(select 1 from public.orders where id=o.id and status='shipped') then raise exception '商家未见出货状态'; end if;
 insert into qa_workspace_results values('一次付款防重、打包出货和商家同步','PASS');
 insert into public.support_tickets(merchant_id,order_id,subject,message) values(m,o.id,'QA回滚工单','QA测试客服闭环，请勿处理') returning id into t;
 rejected:=false;
 begin update public.support_tickets set reply='商家尝试自回复',status='replied' where id=t; exception when others then rejected:=true; end;
 if exists(select 1 from public.support_tickets where id=t and reply is not null) then raise exception '商家自回复未拦截'; end if;
 perform set_config('request.jwt.claim.sub',a::text,true);
 update public.support_tickets set reply='QA运营测试回复',status='replied' where id=t;
 perform set_config('request.jwt.claim.sub',m::text,true);
 if not exists(select 1 from public.support_tickets where id=t and status='replied' and reply='QA运营测试回复') then raise exception '商家未看到回复'; end if;
 insert into qa_workspace_results values('客服提问、管理员回复和商家读取','PASS');
end;
$$;
select * from qa_workspace_results;
rollback;
